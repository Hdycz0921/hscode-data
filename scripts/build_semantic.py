def tokenize(text):
    if not text or not jieba:
        return []
    tokens = []
    for t in jieba.cut(text):
        t = t.strip().lower()
        if not t or t in STOPWORDS:
            continue
        if len(t) >= 2 or t in SIGNIFICANT_SINGLE:
            tokens.append(t)
    return tokens


def load_tariff():
    data = []
    for shard in ['p1.json', 'p2.json', 'p3.json', 'p4.json']:
        fp = os.path.join(TARIFF_IN, shard)
        if not os.path.exists(fp):
            print(f'  警告: 未找到 {fp}')
            continue
        with open(fp, 'r', encoding='utf-8') as f:
            data.extend(json.load(f))
    print(f'  加载 tariff {len(data)} 条')
    return data


def build_inverted_index(data, syn_groups):
    index = {}
    total = len(data)

    def add_posting(tok, code):
        tok = tok.strip().lower()
        if not tok:
            return
        if tok not in index:
            index[tok] = []
        lst = index[tok]
        if not lst or lst[-1] != code:
            lst.append(code)

    for item in data:
        code = item.get('code', '')
        name = item.get('name', '')
        aliases = item.get('a', []) or []

        for tok in tokenize(name + ' ' + ' '.join(aliases)):
            add_posting(tok, code)
        for als in aliases:
            if als:
                add_posting(als, code)

    # 同义词组传播
    for group in syn_groups:
        group_terms = [str(t).strip().lower() for t in group if t]
        if not group_terms:
            continue
        matched = set()
        for item in data:
            blob = (str(item.get('name', '')) + ' ' +
                    ' '.join(item.get('a', []) or [])).lower()
            for term in group_terms:
                if term and term in blob:
                    matched.add(item.get('code', ''))
                    break
        for code in matched:
            for term in group_terms:
                add_posting(term, code)

    return index, total


